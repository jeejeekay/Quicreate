  if (-not (Test-Path -LiteralPath $t[0])) { $skipped += "missing: $($t[1])"; continue }
  if ($DryRun) { Write-Host "delete $($t[1])"; $deleted++; continue }
  Remove-Item -LiteralPath $t[0]
  $deleted++
}
if (-not $DryRun) {
  Get-ChildItem -LiteralPath $data -Recurse -Directory | Sort-Object { $_.FullName.Length } -Descending |
    Where-Object { -not (Get-ChildItem -LiteralPath $_.FullName -Force) } | ForEach-Object { Remove-Item -LiteralPath $_.FullName }
}
Write-Host "Moved $moved recipe files, deleted $deleted files."
if ($skipped.Count) { Write-Host "Skipped:"; $skipped | ForEach-Object { Write-Host "  $_" } }
